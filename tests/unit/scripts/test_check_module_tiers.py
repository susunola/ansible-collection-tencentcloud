from __future__ import absolute_import, division, print_function

__metaclass__ = type

import importlib.util
from pathlib import Path

import pytest
import yaml

REPO_ROOT = Path(__file__).resolve().parents[3]
SCRIPT_PATH = REPO_ROOT / "scripts" / "check_module_tiers.py"


def _load_script():
    spec = importlib.util.spec_from_file_location("check_module_tiers", SCRIPT_PATH)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def tiers():
    return _load_script()


@pytest.fixture
def fake_modules(tmp_path, tiers, monkeypatch):
    """Point the script at a throwaway modules dir and allowlist."""
    allowlist = tmp_path / "core-allowlist.yml"
    allowlist.write_text(
        "modules:\n  - vpc\n  - vpc_info\n", encoding="utf-8")
    modules = tmp_path / "modules"
    modules.mkdir()
    monkeypatch.setattr(tiers, "MODULES_DIR", modules)
    monkeypatch.setattr(tiers, "ALLOWLIST", allowlist)
    return modules


def _write_module(fake_modules, name, generated=False):
    marker = (
        "# Generated by scripts/generate_info_modules.py\n"
        if generated else ""
    )
    (fake_modules / (name + ".py")).write_text(
        marker + "DOCUMENTATION = '''\nmodule: %s\n'''\n" % name, encoding="utf-8"
    )


def test_classify_generated(tiers, fake_modules):
    _write_module(fake_modules, "example_info", generated=True)
    assert tiers.classify("example_info") == "generated"


def test_classify_core(tiers, fake_modules):
    _write_module(fake_modules, "vpc")
    assert tiers.classify("vpc") == "core"


def test_classify_unclassified(tiers, fake_modules):
    _write_module(fake_modules, "mystery_module")
    assert tiers.classify("mystery_module") == "unclassified"


def test_check_detects_unclassified(tiers, fake_modules):
    _write_module(fake_modules, "vpc")
    _write_module(fake_modules, "mystery_module")
    problems, result = tiers.check()
    assert result["core"] == ["vpc"]
    assert result["unclassified"] == ["mystery_module"]
    assert any("mystery_module" in problem and "core-allowlist.yml" in problem
               for problem in problems)


def test_check_detects_generated(tiers, fake_modules):
    _write_module(fake_modules, "vpc", generated=True)
    problems, result = tiers.check()
    assert any("generator banner" in problem for problem in problems)
    assert result["generated"] == ["vpc"]


def test_check_detects_stale_allowlist_entry(tiers, fake_modules):
    _write_module(fake_modules, "vpc")
    problems, result = tiers.check()
    assert result["core"] == ["vpc"]
    assert any("vpc_info" in problem and "do not exist" in problem
               for problem in problems)


def test_check_clean(tiers, fake_modules):
    _write_module(fake_modules, "vpc")
    _write_module(fake_modules, "vpc_info")
    problems, result = tiers.check()
    assert problems == []
    assert result["core"] == ["vpc", "vpc_info"]
    assert result["generated"] == []


def test_real_collection_classifies_everything(tiers):
    # Every shipped module must be on docs/core-allowlist.yml; the generator
    # banner count is the remediation freeze's ratchet, not this gate's.
    _problems, result = tiers.check()
    assert result["unclassified"] == []
    allowlist = yaml.safe_load(
        (REPO_ROOT / "docs" / "core-allowlist.yml").read_text(encoding="utf-8"))
    assert sorted(result["core"] + result["generated"]) == sorted(allowlist["modules"])
