def test_main_check_fails_and_names_the_file(tree, links_check, capsys):
    write(tree, "README.md", "[gone](docs/nowhere.md)\n")
    assert links_check.main(["--check"]) == 1
    assert "README.md -> docs/nowhere.md" in capsys.readouterr().err


def test_main_without_check_reports_the_count(tree, links_check, capsys):
    write(tree, "README.md", "[gone](docs/nowhere.md)\n")
    assert links_check.main([]) == 0
    assert "1 relative link(s) checked, 1 broken" in capsys.readouterr().out
