#!/usr/bin/env python3
"""Generate a reviewable module-to-Tencent-Cloud-API action manifest."""

from __future__ import annotations

import argparse
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
MODULES = ROOT / "plugins" / "modules"
OUTPUT = ROOT / "docs" / "cam-actions.yml"
ACTION = re.compile(r"\bclient\.([A-Z][A-Za-z0-9_]+)\b")


def build_manifest():
    modules = {}
    for path in sorted(MODULES.glob("*.py")):
        if path.name == "__init__.py":
            continue
        actions = sorted(set(ACTION.findall(path.read_text(encoding="utf-8"))))
        if actions:
            modules[path.stem] = actions
    return {
        "version": 1,
        "scope": "Statically detected Tencent Cloud SDK client methods; review conditional and dynamically selected operations.",
        "modules": modules,
    }


def render():
    return "# Generated by scripts/generate_cam_actions.py; do not edit manually.\n" + yaml.safe_dump(build_manifest(), allow_unicode=True, sort_keys=True)


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    content = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            print("CAM action manifest is stale; run scripts/generate_cam_actions.py")
            return 1
        print("CAM action manifest is up to date")
        return 0
    OUTPUT.write_text(content, encoding="utf-8")
    print("wrote: %s" % OUTPUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
