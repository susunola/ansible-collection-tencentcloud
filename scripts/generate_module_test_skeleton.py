def _target_path(module_name):
    return TESTS_DIR / ("test_%s.py" % module_name)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--module-test", metavar="MODULE", default=None,
        help="generate a test skeleton for plugins/modules/MODULE.py",
    )
    parser.add_argument(
        "--print", action="store_true",
        help="with --module-test: print the rendered skeleton instead of writing",
    )
    parser.add_argument(
        "--check", action="store_true",
        help="do not write; fail when a committed skeleton (marker still present) drifted",
    )
    args = parser.parse_args(argv)

    if not args.module_test:
        parser.error("--module-test <name> is required")
    name = args.module_test
    try:
        analysis = analyze(name)
    except AnalysisError as exc:
        print("cannot analyze %s: %s" % (name, exc), file=sys.stderr)
        return 1
    rendered = render(analysis)
    target = _target_path(name)

    if args.print:
        sys.stdout.write(rendered)
        return 0

    if target.exists() and MARKER not in target.read_text():
        print("exists and hand-finished: %s (never rewritten)" % target, file=sys.stdout)
        return 0

    if args.check:
        if not target.exists() or target.read_text() != rendered:
            print("stale skeleton: %s (regenerate with --module-test %s)" % (target, name), file=sys.stderr)
            return 1
        print("up to date: %s" % target, file=sys.stdout)
        return 0

    if target.exists() and target.read_text() == rendered:
        print("up to date: %s" % target, file=sys.stdout)
        return 0
    target.write_text(rendered)
    print("wrote skeleton: %s" % target, file=sys.stdout)
    return 0


if __name__ == "__main__":
    sys.exit(main())
