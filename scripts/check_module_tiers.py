"""Module tier governance check.

Every module in ``plugins/modules/`` must belong to exactly one tier; a
module that belongs to none (or to two) fails the check. The assignment is
rule-based so it cannot rot:

* **generated** -- the file carries the generator marker
  ``# Generated by scripts/generate_info_modules.py``. These ``_info``
  modules are produced from SPECS and must never be edited by hand.
* **core** -- hand-written modules listed in CORE_MODULES below. These are
  the quality anchor of the collection: idempotent write modules with check
  mode, diff output, contract tests and unit tests, plus the hand-written
  ``*_info`` modules that the generator cannot express.

A module that is neither generated nor listed is unclassified and fails the
check, so a new module cannot land without a deliberate tier decision.

Run with ``--check`` (used in CI) to exit 1 when any module is unclassified,
misassigned or stale; run without arguments to print the current tier table
for the README/docs.

See ``docs/module_tiers.md`` for the tier definitions and the acceptance
criteria of each tier.
"""

from __future__ import annotations

