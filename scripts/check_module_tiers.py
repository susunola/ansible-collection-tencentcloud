# -*- coding: utf-8 -*-
"""Module allowlist governance check.

After the P1 surface reduction every module in ``plugins/modules/`` must be
on ``docs/core-allowlist.yml`` -- the 2.0.0 core set named by
``docs/REMEDIATION.md``. Two failure modes remain, and both are caught here:

* **unclassified** -- a module on disk is not on the allowlist. Adding a
  module means editing the allowlist in the same pull request, with a
  written justification, so this cannot happen by accident.
* **generated** -- a module carries the old generator banner. Generated
  modules are forbidden in this collection after 2.0.0; the banner is the
  mechanical marker.

Run with ``--check`` (used in CI) to exit 1 on any violation; run without
arguments to print the current classification.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
MODULES_DIR = REPO_ROOT / "plugins" / "modules"
ALLOWLIST = REPO_ROOT / "docs" / "core-allowlist.yml"

GENERATED_MARKER = "# Generated by scripts/generate_info_modules.py"


def allowlist_modules():
    """Return the module names on ``docs/core-allowlist.yml``."""
    data = yaml.safe_load(ALLOWLIST.read_text(encoding="utf-8"))
    return set(data.get("modules") or [])


def discover_modules():
    """Return the names of every module in ``plugins/modules``."""
    return sorted(
        path.stem
        for path in MODULES_DIR.glob("*.py")
        if not path.name.startswith("__")
    )


def classify(module_name, allowed=None):
    """Return the class of *module_name* (generated, core or unclassified)."""
    text = (MODULES_DIR / (module_name + ".py")).read_text(encoding="utf-8")
    if GENERATED_MARKER in text:
        return "generated"
    if module_name in (allowlist_modules() if allowed is None else allowed):
        return "core"
    return "unclassified"


def check():
    """Return (problems, tiers) where tiers maps tier -> sorted modules."""
    problems = []
    allowed = allowlist_modules()
    tiers = {"core": [], "generated": [], "unclassified": []}
    for module_name in discover_modules():
        tier = classify(module_name, allowed)
        tiers[tier].append(module_name)
        if tier == "unclassified":
            problems.append(
                "%s is not on docs/core-allowlist.yml; remove it or add it "
                "to the allowlist in the same pull request" % module_name
            )
        elif tier == "generated":
            problems.append(
                "%s carries the generator banner; generated modules are "
                "forbidden in this collection (docs/REMEDIATION.md)"
                % module_name
            )
    stale = sorted(allowed - set(discover_modules()))
    if stale:
        problems.append(
            "docs/core-allowlist.yml names modules that do not exist: %s"
            % ", ".join(stale)
        )
    return problems, tiers


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true",
        help="do not print the tier table; fail on any inconsistency",
    )
    args = parser.parse_args(argv)

    problems, tiers = check()
    if args.check:
        if problems:
            print("module allowlist problems:", file=sys.stderr)
            for problem in problems:
                print("  - %s" % problem, file=sys.stderr)
            return 1
        print("module allowlist: %d core, %d generated"
              % (len(tiers["core"]), len(tiers["generated"])))
        return 0

    for tier in ("core", "generated", "unclassified"):
        print("%s (%d):" % (tier, len(tiers[tier])))
        for name in tiers[tier]:
            print("  %s" % name)
    if problems:
        print("problems:", file=sys.stderr)
        for problem in problems:
            print("  - %s" % problem, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
