def discover_modules():
    """Return the names of every module in ``plugins/modules``."""
    return sorted(
        path.stem
        for path in MODULES_DIR.glob("*.py")
        if not path.name.startswith("__")
    )


def classify(module_name):
    """Return the tier of *module_name* (generated, core or unclassified)."""
    text = (MODULES_DIR / (module_name + ".py")).read_text(encoding="utf-8")
    if GENERATED_MARKER in text:
        return "generated"
    if module_name in CORE_MODULES:
        return "core"
    return "unclassified"


def check():
    """Return (problems, tiers) where tiers maps tier -> sorted modules."""
    problems = []
    tiers = {"core": [], "generated": [], "unclassified": []}
    for module_name in discover_modules():
        tier = classify(module_name)
        tiers[tier].append(module_name)
        if tier == "unclassified":
            problems.append(
                "%s is neither generated nor listed in CORE_MODULES; add it "
                "to one of the tiers in scripts/check_module_tiers.py"
                % module_name
            )
    generated_as_core = [name for name in tiers["generated"] if name in CORE_MODULES]
    if generated_as_core:
        problems.append(
            "generated modules must not also be listed in CORE_MODULES: %s"
            % ", ".join(sorted(generated_as_core))
        )
    return problems, tiers


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true",
        help="do not print the tier table; fail on any inconsistency",
    )
    args = parser.parse_args(argv)

    problems, tiers = check()
    if args.check:
        if problems:
            print("module tier problems:", file=sys.stderr)
            for problem in problems:
                print("  - %s" % problem, file=sys.stderr)
            return 1
        print("module tiers: %d core, %d generated"
              % (len(tiers["core"]), len(tiers["generated"])))
        return 0

    for tier in ("core", "generated", "unclassified"):
        print("%s (%d):" % (tier, len(tiers[tier])))
        for name in tiers[tier]:
            print("  %s" % name)
    if problems:
        print("problems:", file=sys.stderr)
        for problem in problems:
            print("  - %s" % problem, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
