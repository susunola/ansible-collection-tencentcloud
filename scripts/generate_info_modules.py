def _run_module_source(spec):
    pagination = spec.get("pagination_type", "int")
    if pagination == "token":
        return _run_module_token_source(spec)
    if pagination == "none":
        return _run_module_none_source(spec)
    if pagination == "list":
        return _run_module_list_source(spec)
    argument_spec = _argument_spec_lines(spec)

    mutually_exclusive = ""
    if spec["ids"] and spec["filters"] and not spec.get("ids_action"):
        mutually_exclusive = (f'\n        mutually_exclusive=[("{spec["ids"]["param"]}", "filters")],')

    build_args = ["models"]
    build_args += [f'module.params["{param["name"]}"]' for param in spec["extra_params"]]
    if spec["ids"] and not spec.get("ids_action"):
        build_args.append(f'module.params["{spec["ids"]["param"]}"]')
    if spec["filters"]:
        build_args.append('module.params["filters"]')
    build_args += ["offset", "limit"]
    build_call = f"build_request({', '.join(build_args)})"
    if len(build_call) > 79:
        build_call = "build_request(\n            " + ",\n            ".join(build_args) + ")"

    ids_branch = ""
    if spec.get("ids_action"):
        ids = spec["ids"]
        ids_action = spec.get("ids_action")
        ids_branch = f"""\
    {ids['param']} = module.params["{ids['param']}"]
    if {ids['param']}:
        request = build_describe_request(models, {ids['param']})
        response = sdk_call(module, client.{ids_action['action']}, request)
        items = response.{ids_action['response_items']} or []
        {spec['result_key']} = [serialize_sdk_object(item) for item in items]
        module.exit_json(changed=False, {spec['result_key']}={spec['result_key']},
                         total_count=len({spec['result_key']}))
"""

    builder = "build_list_request(models, offset, limit)" if spec.get("ids_action") else build_call
    builder_lines = f"lambda offset, limit: {builder}"
    if len(builder_lines) > 79:
        builder_lines = ("lambda offset, limit: build_list_request(\n"
                         "            models, offset, limit)" if spec.get("ids_action")
                         else builder_lines)

    return f"""\
def run_module():
    argument_spec = tencentcloud_argument_spec()
    argument_spec.update({{
{argument_spec}
    }})
    module = AnsibleModule(
        argument_spec=argument_spec,{mutually_exclusive}
        supports_check_mode=True,
    )
{_client_setup_source(spec)}{ids_branch}\
    paginator = Paginator(
        module.params["page_size"],
        {builder_lines},
        lambda request: sdk_call(module, client.{spec['action']}, request),
        {_items_lambda(spec)},
        {_total_lambda(spec)},
    )
    item_set, total_count = paginator.fetch_all()
    {spec['result_key']} = [serialize_sdk_object(item) for item in item_set]
    module.exit_json(changed=False, {spec['result_key']}={spec['result_key']}, total_count=total_count)
"""


