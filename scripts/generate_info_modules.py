        "    default: 5",
        "  waiter_delay:",
        "    description: Seconds to wait between state-polling attempts.",
        "    type: int",
        "    default: 5",
        "  waiter_timeout:",
        "    description: Overall timeout in seconds for state polling.",
        "    type: int",
        "    default: 120",
        "  user_agent:",
        "    description:",
        "      - Value appended to the SDK User-Agent header so API usage can",
