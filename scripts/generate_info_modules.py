def _nested_lambda(path):
    """Render a response accessor lambda; dotted paths guard the holder."""
    if "." in path:
        holder, _dot, field = path.partition(".")
        return (f"lambda response: response.{holder}.{field} "
                f"if response.{holder} is not None else None")
    return f"lambda response: response.{path}"


def _total_lambda(spec):
    if spec["response_total"] is None:
        # The API reports no total; pagination stops at the first short page.
        return "lambda response: None"
    return _nested_lambda(spec["response_total"])


def _items_lambda(spec):
    return _nested_lambda(spec["response_items"])


def _argument_spec_lines(spec):
    argument_lines = []
    for param in spec["extra_params"]:
        if param.get("struct"):
            # Nested dict parameter (e.g. Agent) rendered with sub-options so
            # Ansible validates the required sub-fields at argument_spec level.
            sub_entries = []
            for sub in param["struct"]:
                sub_entry = f'{{"type": "{sub["type"]}"'
                if sub.get("required"):
                    sub_entry += ', "required": True'
                sub_entry += "}"
                sub_entries.append(f'                "{sub["key"]}": {sub_entry},')
            entry = '{\n            "type": "dict"'
            if param.get("required"):
                entry += ',\n            "required": True'
            entry += ',\n            "options": {\n'
            entry += "\n".join(sub_entries)
            entry += "\n            },"
            argument_lines.append(f'        "{param["name"]}": {entry}\n        }},')
            continue
        entry = f'{{"type": "{param["type"]}"'
        if param.get("elements"):
            entry += f', "elements": "{param["elements"]}"'
        if param.get("choices"):
            choices = ", ".join(f'"{c}"' if isinstance(c, str) else str(c) for c in param["choices"])
            entry += f", \"choices\": [{choices}]"
        if param.get("required"):
            entry += ', "required": True'
        if "default" in param:
            default = param["default"]
            if isinstance(default, bool):
                rendered = "True" if default else "False"
            elif isinstance(default, int):
                rendered = str(default)
            else:
                rendered = f'"{default}"'
            entry += f", \"default\": {rendered}"
        if param.get("no_log"):
            entry += ', "no_log": True'
        elif param.get("no_log") is False:
            # Explicitly not a secret (e.g. a tag *key* name); documents the
            # intent and silences validate-modules' no-log-needed heuristic.
            entry += ', "no_log": False'
        entry += "}"
        argument_lines.append(f'        "{param["name"]}": {entry},')
    if spec["ids"]:
        ids_entry = '{"type": "list", "elements": "str"'
        if spec["ids"].get("no_log") is False:
            ids_entry += ', "no_log": False'
        ids_entry += "}"
        argument_lines.append(f'        "{spec["ids"]["param"]}": {ids_entry},')
    if spec["filters"]:
        argument_lines.append('        "filters": {"type": "dict", "default": {}},')
    if _page_size_field(spec) is not None:
        argument_lines.append(
            f'        "page_size": {{"type": "int", "default": {spec.get("page_size_default", 100)}}},')
    return "\n".join(argument_lines)


