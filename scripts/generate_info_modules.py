def module_path(spec):
    return MODULES_DIR / f"{spec['module']}.py"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true",
        help="do not write files; fail if a generated module is missing or stale",
    )
    args = parser.parse_args(argv)

    stale = []
    for spec in SPECS:
        path = module_path(spec)
        rendered = render_module(spec)
        if args.check:
            if not path.exists() or path.read_text() != rendered:
                stale.append(path.name)
            continue
        if path.exists() and path.read_text() == rendered:
            print(f"up to date: {path}")
        else:
            path.write_text(rendered)
            print(f"wrote: {path}")

    if stale:
        print("stale generated modules: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
