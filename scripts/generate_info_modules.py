def _documentation(spec):
    lines = [
        "---",
        f"module: {spec['module']}",
        f"short_description: {spec['short_description']}",
        f'version_added: "{spec.get("version_added", VERSION_ADDED)}"',
        f"description: {spec['description']}",
        "options:",
    ]
    for param in spec["extra_params"]:
        lines += [
            f"  {param['name']}:",
            f"    description: {param['doc']}",
            f"    type: {param['type']}",
        ]
        if param.get("required"):
            lines.append("    required: true")
    if spec["ids"]:
        lines += [
            f"  {spec['ids']['param']}:",
            f"    description: {spec['ids']['doc']}",
            "    type: list",
            "    elements: str",
        ]
    if spec["filters"]:
        lines += [
            "  filters:",
            f"    description: {spec['filters']['doc']}",
            "    type: dict",
            "    default: {}",
        ]
    lines += [
        "  page_size:",
        "    description: Number of results requested per API call.",
        "    type: int",
        "    default: 100",
        f"extends_documentation_fragment: {DOC_FRAGMENT}",
        f"author: {AUTHOR}",
    ]
    return "\n".join(lines)


