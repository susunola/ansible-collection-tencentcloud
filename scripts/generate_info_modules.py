def _build_request_source(spec):
    """Render the module-level request builder function(s)."""
    request_class = spec["request_class"]
    if spec.get("ids_action"):
        ids = spec["ids"]
        ids_action = spec.get("ids_action")
        return f"""\
def build_list_request(models, offset, limit):
    request = models.{request_class}()
    request.Offset = offset
    request.Limit = limit
    return request


def build_describe_request(models, {ids['param']}):
    request = models.{ids_action['request_class']}()
    request.{ids['field']} = {ids['param']}
    return request
"""
    pagination = spec.get("pagination_type", "int")
    args = ["models"]
    args += [param["name"] for param in spec["extra_params"]]
    if spec["ids"]:
        args.append(spec["ids"]["param"])
    if spec["filters"]:
        args.append("filters")
    if pagination == "token":
        args += ["next_token", "max_results"]
    else:
        args += ["offset", "limit"]
    lines = [
        f"def build_request({', '.join(args)}):",
        f"    request = models.{request_class}()",
    ]
    if pagination == "page":
        page_number_field = spec.get("page_number_field", "PageNumber")
        lines += [
            f"    request.{page_number_field} = offset // limit + 1",
            f"    request.{_page_size_field(spec)} = limit",
        ]
    elif pagination == "token":
        if _page_size_field(spec) is not None:
            lines.append(f"    request.{_page_size_field(spec)} = max_results")
    elif pagination in ("none", "list"):
        if pagination == "none":
            comment = (f"    # {spec['action']} takes no request arguments and is not\n"
                       "    # paginated; offset and limit are accepted for signature uniformity.")
        else:
            comment = (f"    # {spec['action']} returns the full list in one call and is not\n"
                       "    # paginated; offset and limit are accepted for signature uniformity.")
        lines.insert(1, comment)
    else:
        lines += [
            "    request.Offset = offset",
            f"    request.{_page_size_field(spec)} = limit",
        ]
    for param in spec["extra_params"]:
        if param.get("struct"):
            # dict parameter rendered as an SDK model object (e.g. Agent).
            obj = f"_{param['name']}_obj"
            lines.append(f"    if {param['name']} is not None:")
            lines.append(f"        {obj} = models.{param['model']}()")
            for sub in param["struct"]:
                sub_field = sub["field"].split(".")[-1]
                if sub.get("holder"):
                    lines.append(f"        {obj}.{sub['holder']} = models.{sub['holder_model']}()")
                    lines.append(
                        f"        {obj}.{sub['holder']}.{sub_field} = "
                        f"{param['name']}.get({sub['key']!r})")
                else:
                    lines.append(
                        f"        {obj}.{sub['field']} = "
                        f"{param['name']}.get({sub['key']!r})")
            lines.append(f"        request.{param['field']} = {obj}")
        elif param.get("required") or "default" in param:
            lines.append(f"    request.{param['field']} = {param['name']}")
        else:
            lines += [
                f"    if {param['name']} is not None:",
                f"        request.{param['field']} = {param['name']}",
            ]
    if spec["ids"]:
        lines += [
            f"    if {spec['ids']['param']}:",
            f"        request.{spec['ids']['field']} = {spec['ids']['param']}",
        ]
    if spec["filters"]:
        filter_model = spec["filters"].get("model", "Filter")
        name_field = spec["filters"].get("name_field", "Name")
        value_field = spec["filters"].get("value_field", "Values")
        if spec["filters"].get("name_wrap"):
            name_value = "[name]"
        else:
            name_value = "name"
        lines += [
            "    if filters:",
            "        request.Filters = []",
            "        for name, values in sorted(filters.items()):",
            f"            api_filter = models.{filter_model}()",
            f"            api_filter.{name_field} = {name_value}",
            f"            api_filter.{value_field} = values if isinstance(values, list) else [values]",
            "            request.Filters.append(api_filter)",
        ]
    if pagination == "token":
        token_field = spec.get("token_request_field", "NextToken")
        lines += [
            "    if next_token:",
            f"        request.{token_field} = next_token",
        ]
    lines.append("    return request")
    return "\n".join(lines) + "\n"


def _nested_lambda(path):
    """Render a response accessor lambda; dotted paths guard the holder."""
    if "." in path:
        holder, _dot, field = path.partition(".")
        return (f"lambda response: response.{holder}.{field} "
                f"if response.{holder} is not None else None")
    return f"lambda response: response.{path}"


def _total_lambda(spec):
    if spec["response_total"] is None:
        # The API reports no total; pagination stops at the first short page.
        return "lambda response: None"
    return _nested_lambda(spec["response_total"])


def _items_lambda(spec):
    return _nested_lambda(spec["response_items"])


def _argument_spec_lines(spec):
    argument_lines = []
    for param in spec["extra_params"]:
        if param.get("struct"):
            # Nested dict parameter (e.g. Agent) rendered with sub-options so
            # Ansible validates the required sub-fields at argument_spec level.
            sub_entries = []
            for sub in param["struct"]:
                sub_entry = f'{{"type": "{sub["type"]}"'
                if sub.get("required"):
                    sub_entry += ', "required": True'
                sub_entry += "}"
                sub_entries.append(f'                "{sub["key"]}": {sub_entry},')
            entry = '{\n            "type": "dict"'
            if param.get("required"):
                entry += ',\n            "required": True'
            entry += ',\n            "options": {\n'
            entry += "\n".join(sub_entries)
            entry += "\n            },"
            argument_lines.append(f'        "{param["name"]}": {entry}\n        }},')
            continue
        entry = f'{{"type": "{param["type"]}"'
        if param.get("required"):
            entry += ', "required": True'
        if "default" in param:
            default = param["default"]
            if isinstance(default, bool):
                rendered = "True" if default else "False"
            elif isinstance(default, int):
                rendered = str(default)
            else:
                rendered = f'"{default}"'
            entry += f", \"default\": {rendered}"
        entry += "}"
        argument_lines.append(f'        "{param["name"]}": {entry},')
    if spec["ids"]:
        ids_entry = '{"type": "list", "elements": "str"'
        if spec["ids"].get("no_log") is False:
            ids_entry += ', "no_log": False'
        ids_entry += "}"
        argument_lines.append(f'        "{spec["ids"]["param"]}": {ids_entry},')
    if spec["filters"]:
        argument_lines.append('        "filters": {"type": "dict", "default": {}},')
    if _page_size_field(spec) is not None:
        argument_lines.append(
            f'        "page_size": {{"type": "int", "default": {spec.get("page_size_default", 100)}}},')
    return "\n".join(argument_lines)


def _client_setup_source(spec):
    return f"""\
    try:
        from {spec['service_package']} import models, {spec['client_module']}
    except ImportError:
        module.fail_json(msg="The {spec['sdk_package']} package is required.")

    client = {spec['client_module']}.{spec['client_class']}(
        create_credential(module), module.params["region"],
        create_client_profile(module, "{spec['endpoint']}"),
    )
"""


def _run_module_token_source(spec):
    """Render run_module for token-paginated APIs (cloudaudit, alb, ...).

    Field names come from the spec so products whose continuation token is
    not called NextToken (ams PageToken, chdfs FileSystemIdMarker, faceid
    Cursor) share the same loop; cloudaudit keeps the default field names.
    """
    token_response_field = spec.get("token_response_field", "NextToken")
    list_over_field = spec.get("list_over_field", "ListOver")
    has_more_field = spec.get("has_more_field")
    if list_over_field:
        termination = f"response.{list_over_field} or not next_token"
    elif has_more_field:
        termination = f"not response.{has_more_field} or not next_token"
    else:
        termination = "not next_token"
    if spec["response_total"] is not None:
        total_lines = (f"        if total_count is None and response.{spec['response_total']} is not None:\n"
                       f"            total_count = response.{spec['response_total']}\n")
    else:
        total_lines = ""
    page_size_arg = ('module.params["page_size"]' if _page_size_field(spec) is not None
                     else "None")
    build_args = ["models"]
    build_args += [f'module.params["{param["name"]}"]' for param in spec["extra_params"]]
    build_args += ["next_token", page_size_arg]
    build_call = "build_request(\n            " + ",\n            ".join(build_args) + ")"
    argument_lines = _argument_spec_lines(spec)
    if argument_lines:
        update = f"argument_spec.update({{\n{argument_lines}\n    }})"
    else:
        update = "argument_spec.update({})"
    return f"""\
def run_module():
    argument_spec = tencentcloud_argument_spec()
    {update}
    module = AnsibleModule(
        argument_spec=argument_spec,
        supports_check_mode=True,
    )
{_client_setup_source(spec)}    {spec['result_key']} = []
    next_token = None
    total_count = None
    while True:
        request = {build_call}
        response = sdk_call(module, client.{spec['action']}, request)
        batch = response.{spec['response_items']} or []
        {spec['result_key']}.extend(serialize_sdk_object(item) for item in batch)
{total_lines}        next_token = response.{token_response_field}
        if {termination}:
            break
    if total_count is None:
        total_count = len({spec['result_key']})
    module.exit_json(changed=False, {spec['result_key']}={spec['result_key']}, total_count=total_count)
"""


def _run_module_list_source(spec):
    """Render run_module for unpaginated list APIs (advisor, captcha).

    Unlike "none" (billing) the response carries an items list; the whole
    list is returned by a single call and total_count is its length.
    """
    items_expr = spec["response_items"]
    if "." in items_expr:
        holder, _dot, field = items_expr.partition(".")
        items_expr = (f"(response.{holder}.{field} "
                      f"if response.{holder} is not None else None)")
    else:
        items_expr = f"response.{items_expr}"
    argument_lines = _argument_spec_lines(spec)
    if argument_lines:
        update = f"argument_spec.update({{\n{argument_lines}\n    }})"
    else:
        update = "argument_spec.update({})"
    return f"""\
def run_module():
    argument_spec = tencentcloud_argument_spec()
    {update}
    module = AnsibleModule(
        argument_spec=argument_spec,
        supports_check_mode=True,
    )
{_client_setup_source(spec)}    request = build_request(models, 0, 0)
    response = sdk_call(module, client.{spec['action']}, request)
    items = {items_expr} or []
    {spec['result_key']} = [serialize_sdk_object(item) for item in items]
    module.exit_json(changed=False, {spec['result_key']}={spec['result_key']},
                     total_count=len({spec['result_key']}))
"""


