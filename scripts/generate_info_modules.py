def _load_auto_specs():
    """Load auto-discovered specs from ``scripts/info_specs_auto.py``.

    The file is written by ``scripts/discover_info_specs.py``. Loading it by
    path (rather than a plain import) keeps the combined spec list available
    when this script is exec'd via importlib by the contract/unit tests.
    """
    path = Path(__file__).with_name("info_specs_auto.py")
    if not path.exists():
        return []
    spec = importlib.util.spec_from_file_location("info_specs_auto", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return list(module.SPECS_AUTO)


