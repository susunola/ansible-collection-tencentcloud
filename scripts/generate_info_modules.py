"""Generate read-only ``*_info`` modules for Tencent Cloud services.

Every generated module mirrors ``plugins/modules/subnet_info.py``: a
``build_request`` helper plus a ``run_module`` that pages through the
service's describe/list API with ``module_utils.paging.Paginator``.

The generator is re-runnable: rewriting a module with identical content
leaves the file untouched. Run with ``--check`` to verify the generated
modules are up to date (used in CI).

Field names, request/response shapes and pagination types in SPECS were
verified by introspecting the ``tencentcloud-sdk-python-<service>``
packages; do not edit them by guesswork.

Auto-discovered specs live in ``scripts/info_specs_auto.py`` (written by
``scripts/discover_info_specs.py``) and are appended to SPECS at import
time; curated SPECS stay untouched and their output remains byte-identical.

For every spec that fits the simple offset/limit or page-number shape the
generator also emits a unit test file (``tests/unit/plugins/modules/
test_<module>.py``); test files without the generated marker are considered
hand-finished and are never rewritten.

Write modules cannot be generated end-to-end (idempotency, drift
comparison and required-field constraints are per-resource decisions the
SDK models do not encode), so the generator also scaffolds them: given a
curated ``RESOURCE_SPECS`` entry it introspects the SDK request models and
renders the module boilerplate -- argument spec and request builders --
for the developer to finish. Run ``--resource <module>`` to scaffold;
scaffolding is write-once and never touches an existing module file.
"""

